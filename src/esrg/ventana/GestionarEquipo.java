    public void updateTable() {
        for (int i = 0; i < tbl_equipo.getRowCount(); i++) {
            model.removeRow(i);
            i -= 1;
        }

        try {
            Connection cn = Conexion.conexion();
            PreparedStatement ps = cn.prepareStatement(
                    "select id_equipo, tipo_equipo, marca, estatus from equipos");

            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                Object[] filas = new Object[4];
                for (int i = 0; i < 4; i++) {
                    filas[i] = rs.getObject(i + 1);
                }
                model.addRow(filas);
            }

            cn.close();
        } catch (SQLException er) {
            System.err.println("Error: " + er);
        }
    }

    public void searchFilter() {
        tbl_equipo.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = tbl_equipo.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    table_update = (int) model.getValueAt(fila_point, columna_point);
                    //JOptionPane.showMessageDialog(null, "el id del cliente seleccionando es: " + table_update);
                    new InformacionEquipoTecnico().setVisible(true);
                }
            }
        });
    }
