    private void cmb_estatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmb_estatusActionPerformed

        for (int i = 0; i < tbl_equipo.getRowCount(); i++) {
            model.removeRow(i);
            i -= 1;
        }

        String selection = cmb_estatus.getSelectedItem().toString();
        String query = "";

        if (selection.equals("Todos")) {
            query = "select id_equipo, tipo_equipo, marca, estatus from equipos";
        } else {
            query = "select id_equipo, tipo_equipo, marca, estatus from equipos where estatus = '" + selection + "'";
        }

        try {
            Connection cn = Conexion.conexion();
            PreparedStatement ps = cn.prepareStatement(query);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                do {
                    Object fila[] = new Object[4];
                    for (int i = 0; i < 4; i++) {
                        fila[i] = rs.getObject(i + 1);
                    }
                    model.addRow(fila);
                } while (rs.next());
            }

            cn.close();

        } catch (SQLException e) {
            System.err.println("Error " + e);
        }
    }//GEN-LAST:event_cmb_estatusActionPerformed

